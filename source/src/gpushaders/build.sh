#!/bin/sh
# Compiles the GPU backend's GLSL shaders (this directory), every variant the backend uses, for SDL GPU's Vulkan driver
# (SPIR-V) and Direct3D 12 driver (DXBC, shader model 5.1), and writes them as C arrays to ../gfx_sdlgpu_spirv.h and
# ../gfx_sdlgpu_dxbc.h. The headers are committed, so building the game doesn't need any of the tools: run this after
# changing a shader here (and its MSL twin in gfx_sdlgpu.cpp).
# Needs glslangValidator (glslang); spirv-val (SPIRV-Tools) validates each SPIR-V module if it's installed. The DXBC
# needs spirv-cross (SPIR-V -> HLSL, which keeps SDL GPU's binding model: Vulkan descriptor set n is D3D12 register
# space n) and vkd3d-compiler (vkd3d 1.19 or newer: HLSL -> DXBC); without them only the SPIR-V header is written.
# Fedora 45 has all of them but spirv-cross, which builds from its sources in a minute.
# usage: build.sh [SPIR-V header] [DXBC header] (default: ../gfx_sdlgpu_spirv.h, ../gfx_sdlgpu_dxbc.h)
set -e
here=$(cd "$(dirname "$0")" && pwd)
if [ -n "$1" ]; then out=$(cd "$(dirname "$1")" && pwd)/$(basename "$1"); else out=$(dirname "$here")/gfx_sdlgpu_spirv.h; fi
if [ -n "$2" ]; then dxout=$(cd "$(dirname "$2")" && pwd)/$(basename "$2"); else dxout=$(dirname "$here")/gfx_sdlgpu_dxbc.h; fi
dxbc=""
if command -v spirv-cross > /dev/null && command -v vkd3d-compiler > /dev/null; then dxbc=1; else echo "(no spirv-cross or vkd3d-compiler: SPIR-V only)"; fi
cd "$here"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
table=""
# compile <file> <stage> <name> <variant> <defines...>
compile()
{
    file=$1; stage=$2; name=$3; variant=$4; shift 4
    var=spv_$(echo "$name" | tr . _)_$variant
    glslangValidator -V --target-env vulkan1.0 -S "$stage" "$@" --vn "$var" -o "$tmp/$var.h" "$file" > "$tmp/log" || { cat "$tmp/log"; exit 1; }
    glslangValidator -V --target-env vulkan1.0 -S "$stage" "$@" -o "$tmp/$var.spv" "$file" > /dev/null
    if command -v spirv-val > /dev/null; then spirv-val --target-env vulkan1.0 "$tmp/$var.spv"; fi
    grep -v '#pragma once' "$tmp/$var.h" | grep -v '^[[:space:]]*//' >> "$tmp/arrays"
    table="$table    { \"$name\", $variant, $var, sizeof($var) },
"
    if [ -n "$dxbc" ]; then
        dvar=dxbc_$(echo "$name" | tr . _)_$variant
        if [ "$stage" = vert ]; then profile=vs_5_1; else profile=ps_5_1; fi
        spirv-cross --hlsl --shader-model 51 "$tmp/$var.spv" --output "$tmp/$var.hlsl"
        vkd3d-compiler -x hlsl -p "$profile" -b dxbc-tpf -e main -o "$tmp/$var.dxbc" "$tmp/$var.hlsl" > "$tmp/log" 2>&1 || { cat "$tmp/log"; exit 1; }
        {
            echo "static const uint8_t $dvar[] = {"
            od -An -v -tx1 "$tmp/$var.dxbc" | sed -e 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g' -e 's/^/    /'
            echo "};"
        } >> "$tmp/dxbcarrays"
        dtable="$dtable    { \"$name\", $variant, $dvar, sizeof($dvar) },
"
    fi
}
: > "$tmp/arrays"
: > "$tmp/dxbcarrays"
dtable=""
# scene.vert: 1 = texture coordinates, 2 = colours, 4 = unit 1's coordinates (not with 16), 8 = texture matrices,
# 16 = smooth line
v=0
while [ $v -lt 32 ]; do
    if [ $((v & 4)) -eq 0 ] || [ $((v & 16)) -eq 0 ]; then
        compile scene.vert vert scene.vert $v -DHAS_TC=$((v & 1)) -DHAS_COLOR=$(((v >> 1) & 1)) -DHAS_TC1=$(((v >> 2) & 1)) -DTEXMAT=$(((v >> 3) & 1)) -DLINEAA=$(((v >> 4) & 1))
    fi
    v=$((v + 1))
done
# scene.frag, and the pick pass's version: 1 = texture matrices, 2 = smooth line
for f in 0 1 2 3; do
    compile scene.frag frag scene.frag $f -DTEXMAT=$((f & 1)) -DLINEAA=$(((f >> 1) & 1)) -DPICK=0
    compile scene.frag frag pick.frag $f -DTEXMAT=$((f & 1)) -DLINEAA=$(((f >> 1) & 1)) -DPICK=1
done
compile post.vert vert post.vert 0
compile gamma.frag frag gamma.frag 0
compile fxaa.frag frag fxaa.frag 0
{
    echo "// Generated by gpushaders/build.sh from gpushaders/*.vert, *.frag ($(glslangValidator --version | head -1 | sed 's/^Glslang Version: //'));"
    echo "// don't edit. SPIR-V for SDL GPU's Vulkan driver (see gfx_sdlgpu.cpp, makeshader())."
    echo
    echo "#include <stddef.h>"
    echo "#include <stdint.h>"
    echo
    cat "$tmp/arrays"
    echo
    echo "struct gpuspirv { const char *name; int variant; const uint32_t *code; size_t size; };"
    echo "static const gpuspirv gpuspirvshaders[] ="
    echo "{"
    printf "%s" "$table"
    echo "};"
} > "$out"
echo "wrote $out"
if [ -n "$dxbc" ]; then
    {
        echo "// Generated by gpushaders/build.sh from gpushaders/*.vert, *.frag (glslang $(glslangValidator --version | head -1 | sed 's/^Glslang Version: //'),"
        echo "// SPIRV-Cross, $(vkd3d-compiler --version | head -1)); don't edit."
        echo "// DXBC (shader model 5.1) for SDL GPU's Direct3D 12 driver (see gfx_sdlgpu.cpp, makeshader())."
        echo
        echo "#include <stddef.h>"
        echo "#include <stdint.h>"
        echo
        cat "$tmp/dxbcarrays"
        echo
        echo "struct gpudxbc { const char *name; int variant; const uint8_t *code; size_t size; };"
        echo "static const gpudxbc gpudxbcshaders[] ="
        echo "{"
        printf "%s" "$dtable"
        echo "};"
    } > "$dxout"
    echo "wrote $dxout"
fi
